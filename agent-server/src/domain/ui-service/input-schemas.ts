const FORBIDDEN_PROVIDER_KEYS = new Set(['__proto__', 'prototype', 'constructor']);
const MAX_PROVIDER_KEY_LENGTH = 120;

const settingTypeSchemas = {
  boolean: z.boolean(),
  number: z.number().finite(),
  'number|null': z.number().finite().nullable(),
  'string[]': z.array(z.string()),
  'string|null': z.string().nullable(),
} as const;

// providerRateLimits is not writable through config.set; it has its own mutation.
type WritableSettingKey = Exclude<keyof typeof SETTINGS_SPEC, 'providerRateLimits'>;
type WritableSettingSpec = (typeof SETTINGS_SPEC)[WritableSettingKey];

type SettingsShape = {
  [K in WritableSettingKey]:
    (typeof settingTypeSchemas)[(typeof SETTINGS_SPEC)[K]['type']];
};

function settingSchema(spec: WritableSettingSpec): z.ZodTypeAny {
  const base = settingTypeSchemas[spec.type];
  if (!('validate' in spec) || typeof spec.validate !== 'function') return base;
  return base.superRefine((value, ctx) => {
    const message = spec.validate(value as never);
    if (!message) return;
    ctx.addIssue({ code: z.ZodIssueCode.custom, message });
  });
}

const settingsShape = Object.fromEntries(
  (Object.entries(SETTINGS_SPEC) as [keyof typeof SETTINGS_SPEC, WritableSettingSpec][])
    .filter(([key]) => key !== 'providerRateLimits')
    .map(([key, spec]) => [key, settingSchema(spec)]),
) as unknown as Record<string, SettingsShape[WritableSettingKey]>;

function rejectUndefinedSettings(value: Record<string, unknown>, ctx: z.RefinementCtx): void {
  for (const [key, setting] of Object.entries(value)) {
    if (setting !== undefined) continue;
    ctx.addIssue({
      code: z.ZodIssueCode.custom,
      path: [key],
      message: 'setting must not be undefined',
    });
  }
}

const settingsValueInput = z.object(settingsShape).partial().strict()
  .superRefine(rejectUndefinedSettings);

// config.set: a discriminated union of the safely-writable sections. `budget` numbers must be
// finite and positive; `settings` accepts only finite,
// spec-typed partial overrides. Any section or settings key outside this union is rejected.
//
// `budget` targets the global limits by default, or one project's override when `project` is given.
// Overrides are pair-only (both limits or neither), so `value` is never partial. An ABSENT (or
// null) `value` means "clear this project's override" — meaningless, and destructive-looking,
// without a `project`, so that combination is rejected. Both `project` and `value` accept null as
// well as undefined because the generated tRPC client types collapse nullable optionals to
// `undefined`, while direct in-process callers naturally pass null.
export const configSetInput = z.discriminatedUnion('section', [
  z.object({
    section: z.literal('budget'),
    project: z.string().min(1).nullish(),
    value: z.object({
      daily_usd: z.number().finite().positive(),
      monthly_usd: z.number().finite().positive(),
    }).nullish(),
  }).superRefine((v, ctx) => {
    if (v.value == null && !v.project) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ['value'],
        message: 'a budget write without a value clears a per-project override and requires `project`',
      });
    }
  }),
  z.object({
    section: z.literal('settings'),
    value: settingsValueInput,
  }),
  // The language knob lives in config/preferences.json, not settings.json, and writing it also
  // switches the live server locale — so it is its own section rather than a settings key.
  z.object({
    section: z.literal('preferences'),
    value: z.object({
      lang: z.enum(['en', 'zh']),
    }),
  }),
]);

